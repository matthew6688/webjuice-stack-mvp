#!/usr/bin/env node
/**
 * pl:provenance-annotate · codex R84 (P2-1c-machine) · inject data-provenance / data-replace
 * onto rendered sections for PREVIEW/audit/overlay use.
 *
 * LIVE HARD-OFF by construction (codex R83 §5): this writes a SEPARATE preview artifact
 * (index.preview-annotated.html) and NEVER touches the live editorial-output/index.html.
 * It is a post-processor — does NOT change the composer or template render logic.
 *
 * Reads: editorial-output/index.html + provenance-map.json (pl:provenance-map).
 * Per rendered <section>, aggregates the WORST replace_policy + dominant tier and injects
 * `data-provenance` / `data-replace` / `data-prov-detail`. missing_sections (no real content)
 * → data-replace="replace_required" data-provenance="missing_real_content".
 *
 * Usage: node scripts/cli/pl-provenance-annotate.js --slug <slug> [--json]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
process.chdir(REPO);
const argv = process.argv.slice(2);
const slug = (() => { const i = argv.indexOf('--slug'); return i >= 0 ? argv[i + 1] : null; })();
const JSON_OUT = argv.includes('--json');
if (!slug) { console.error('--slug required'); process.exit(1); }
const V2 = `clients/${slug}/v2`;
const readJson = (p) => { try { return JSON.parse(fs.readFileSync(path.resolve(p), 'utf8')); } catch { return null; } };

const pmap = readJson(`${V2}/provenance-map.json`);
if (!pmap) { console.error(`✗ no provenance-map.json — run pl:provenance-map --slug ${slug} first`); process.exit(2); }
const htmlPath = path.resolve(`${V2}/editorial-output/index.html`);
let html;
try { html = fs.readFileSync(htmlPath, 'utf8'); } catch { console.error(`✗ no rendered index.html — run pl:compose-editorial first`); process.exit(3); }

// provenance section name → rendered HTML section id
const SECTION_MAP = { hero: 'top', services: 'services', suburbs: 'coverage', reviews: 'reviews', images: 'gallery' };
const POLICY_RANK = { none: 0, confirm: 1, replace_required: 2 };
const TIER_RANK = { verified: 0, geo_derived: 1, ai_inferred: 2, ai_placeholder: 3, stock_placeholder: 4 };

// aggregate per provenance-section: worst policy + worst (least-trusted) tier + counts
const agg = {};
for (const e of pmap.sections || []) {
  const a = agg[e.section] || (agg[e.section] = { policy: 'none', tier: 'verified', counts: {} });
  if (POLICY_RANK[e.replace_policy] > POLICY_RANK[a.policy]) a.policy = e.replace_policy;
  if (TIER_RANK[e.tier] > TIER_RANK[a.tier]) a.tier = e.tier;
  a.counts[e.tier] = (a.counts[e.tier] || 0) + 1;
}
// missing sections override → replace_required
for (const m of pmap.missing_sections || []) agg[m.section] = { policy: 'replace_required', tier: 'missing_real_content', counts: { missing: 1 }, missing: true };

const applied = [];
let out = html;
for (const [provSection, htmlId] of Object.entries(SECTION_MAP)) {
  const a = agg[provSection];
  if (!a) continue;
  const detail = a.missing ? (pmap.missing_sections.find((m) => m.section === provSection)?.expected || 'provide real content')
    : Object.entries(a.counts).map(([t, n]) => `${t}:${n}`).join(',');
  const attrs = `data-provenance="${a.tier}" data-replace="${a.policy}" data-prov-detail="${detail.replace(/"/g, '')}"`;
  // match the whole <section ...id="htmlId"...> open tag · insert attrs after <section (idempotent)
  const re = new RegExp(`<section\\b((?:(?!>)[\\s\\S])*?\\bid="${htmlId}"(?:(?!>)[\\s\\S])*?)>`);
  const before = out;
  out = out.replace(re, (m, inner) => inner.includes('data-provenance') ? m : `<section ${attrs}${inner}>`);
  if (out !== before) applied.push({ section: provSection, htmlId, ...a, detail });
}

if (JSON_OUT) { console.log(JSON.stringify({ slug, applied }, null, 2)); process.exit(0); }

const outPath = path.resolve(`${V2}/editorial-output/index.preview-annotated.html`);
const banner = `<!-- PREVIEW PROVENANCE ANNOTATION · codex R84 · NOT FOR LIVE · generated by pl:provenance-annotate · data-replace=replace_required ⇒ client must swap real content before launch -->\n`;
fs.writeFileSync(outPath, banner + out);
console.log(`\n=== provenance-annotate · ${slug} (PREVIEW · live index.html untouched) ===`);
applied.forEach((a) => console.log(`  #${a.htmlId.padEnd(10)} provenance=${a.tier.padEnd(18)} replace=${a.policy.padEnd(16)} (${a.detail})`));
console.log(`\n✓ → ${path.relative(REPO, outPath)}  · live ${path.relative(REPO, htmlPath)} unchanged`);
